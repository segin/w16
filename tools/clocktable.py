#!/usr/bin/env python3
"""clocktable - w16 Clock's circle table, computed, and checked against
what the original passes to GDI.

The table holds 60 points on a circle of radius 8000, clockwise from
12 o'clock at 6-degree steps: x = 8000 sin(6i deg), y = -8000 cos(6i deg),
rounded to the nearest integer. Windows 3.1's Clock positions its hour
marks, minute dots and hands by MulDiv(table value, radius, 8000), so the
values it uses are visible as the first arguments of those MulDiv calls
in a GD2 log of its drawing (tests/refrun.sh with REFRUN_GDLOG=1). A few
of them are one less in magnitude than the rounded value; CORRECTIONS
lists each, with the observation behind it (ARCHITECTURE.md 15.2).

usage: clocktable.py OUT.H         write the table as C (face.c includes it)
       clocktable.py --check CALLS compare with the MulDiv arguments in a
                                   tools/gdcalls.py listing of the original
                                   drawing its analog face (one paint of
                                   the 60 marks and dots: y first, then x)
"""
import math
import sys

# (index, 'x' or 'y'): value. Observed: in the original's paint of its
# analog face (GD2 log, 10:09:30, the CK2 window sizes: the same
# arguments at each) the MulDiv calls that place the marks and dots pass
# these, one less in magnitude than rounding gives.
CORRECTIONS = {
    (0, 'y'): -7999,    # the 12 o'clock mark
    (4, 'x'): 3253,     # the dot at 4 minutes
    (5, 'x'): 3999,     # the 1 o'clock mark
    (11, 'y'): -3253,   # the dot at 11 minutes
    (19, 'y'): 3253,    # 19
    (25, 'x'): 3999,    # the 5 o'clock mark
    (26, 'x'): 3253,    # 26
    (30, 'y'): 7999,    # the 6 o'clock mark
    (34, 'x'): -3253,   # 34
    (40, 'y'): 3999,    # the 8 o'clock mark
    (41, 'y'): 3253,    # 41
    (45, 'x'): -7999,   # the 9 o'clock mark
    (49, 'y'): -3253,   # 49
    (55, 'x'): -3999,   # the 11 o'clock mark
    (56, 'x'): -3253,   # 56
}


def computed():
    t = []
    for i in range(60):
        a = math.radians(6 * i)
        t.append([int(round(8000 * math.sin(a))), int(round(-8000 * math.cos(a)))])
    return t


def table():
    t = computed()
    for (i, c), v in CORRECTIONS.items():
        t[i][0 if c == 'x' else 1] = v
    return t


def observed(path):
    vals = []
    for l in open(path):
        p = l.split()
        if len(p) == 4 and p[0] == 'MULDIV' and p[3] == '1F40':
            v = int(p[1], 16)
            vals.append(v - 65536 if v > 32767 else v)
            if len(vals) == 120:
                break
    return [(vals[2 * i + 1], vals[2 * i]) for i in range(60)]   # (x, y)


def main():
    if len(sys.argv) > 2 and sys.argv[1] == '--check':
        obs = observed(sys.argv[2])
        c = computed()
        for i in range(60):
            for k, n in ((0, 'x'), (1, 'y')):
                if obs[i][k] != c[i][k]:
                    print('%2d %s computed %6d observed %6d' % (i, n, c[i][k], obs[i][k]))
        t = table()
        bad = sum(1 for i in range(60) for k in (0, 1) if t[i][k] != obs[i][k])
        print('table vs observed: %d differences' % bad)
        sys.exit(1 if bad else 0)
    t = table()
    with open(sys.argv[1], 'w') as f:
        f.write('/* generated by tools/clocktable.py: 60 points on a circle of radius\n'
                '   8000, x then y, clockwise from 12 o\'clock */\n')
        for i in range(0, 60, 5):
            f.write('    ' + ' '.join('%6d, %6d,' % tuple(t[j]) for j in range(i, i + 5)) + '\n')


if __name__ == '__main__':
    main()
