#!/usr/bin/env python3
"""exports - build w16's export reference tables (docs/exports/*.txt).

For each system module, one line per ordinal that exists on Windows 3.1
or Windows/386 2.11:

    ordinal  3.1  2.11  convention  name

- Existence is observed black-box with tests/apps/texp.c (GetProcAddress
  by ordinal) on the reference installs: build/ref/texp31S.txt (Windows
  3.1; Standard and 386 Enhanced mode agree) and build/ref/texp-w386.txt.
- Names come first from OpenWatcom's import libraries
  (build/host/imports.txt, tools/omfimp.py; OWPL), then from Wine's
  X11-licensed spec files of wine-20020228, the last release before
  Wine's move to the LGPL (.tools/wine/specs, see ARCHITECTURE.md 3).
  The calling convention column is Wine's (pascal, pascal16, register,
  equate, stub, ...) and is blank where Wine has no entry.

usage: exports.py OUTDIR
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OBS = {'3.1': 'build/ref/texp31S.txt', '2.11': 'build/ref/texp-w386.txt'}
SPECS = '.tools/wine/specs'
SPEC_FILE = {'KERNEL': 'kernel', 'USER': 'user', 'GDI': 'gdi', 'KEYBOARD': 'keyboard',
             'SYSTEM': 'system', 'SOUND': 'sound', 'DISPLAY': 'display', 'MOUSE': 'mouse',
             'COMM': 'comm', 'WIN87EM': 'win87em', 'SHELL': 'shell', 'COMMDLG': 'commdlg',
             'TOOLHELP': 'toolhelp', 'DDEML': 'ddeml', 'LZEXPAND': 'lzexpand', 'VER': 'ver',
             'MMSYSTEM': 'mmsystem'}


def observed(path):
    """{module: set(ordinals)} from a TEXP log; absent modules omitted."""
    mods = {}
    for line in open(os.path.join(ROOT, path)):
        p = line.split()
        if len(p) < 2 or p[0] != 'EXP' or (len(p) > 2 and p[2] == 'absent'):
            continue
        s = set()
        for r in p[2:]:
            a, _, b = r.partition('-')
            s.update(range(int(a), int(b or a) + 1))
        mods[p[1]] = s
    return mods


def watcom_names():
    names = {}
    path = os.path.join(ROOT, 'build/host/imports.txt')
    if os.path.exists(path):
        for line in open(path):
            p = line.split()
            if len(p) >= 3 and p[1].isdigit():
                names.setdefault((p[0], int(p[1])), p[2])
    return names


def wine_entries(mod):
    """{ordinal: (convention, name)} from Wine's spec for mod."""
    f = SPEC_FILE.get(mod)
    out = {}
    if not f:
        return out
    path = os.path.join(ROOT, SPECS, f + '.spec')
    if not os.path.exists(path):
        return out
    for line in open(path, encoding='latin-1'):
        m = re.match(r'^\s*(\d+)\s+(\S+)\s+(\S+)', line)
        if not m:
            continue
        conv, name = m.group(2), m.group(3)
        name = name.split('(')[0]
        if conv == 'stub' or conv == 'equate' or conv == 'variable':
            pass
        out[int(m.group(1))] = (conv, name)
    return out


def main():
    outdir = sys.argv[1]
    os.makedirs(outdir, exist_ok=True)
    obs = {v: observed(p) for v, p in OBS.items()}
    wat = watcom_names()
    mods = sorted(set(obs['3.1']) | set(obs['2.11']))
    for mod in mods:
        wine = wine_entries(mod)
        o31 = obs['3.1'].get(mod, set())
        o211 = obs['2.11'].get(mod, set())
        lines = ['# %s exports: ordinal, present on Windows 3.1, on Windows/386 2.11,' % mod,
                 '# Wine calling convention, name. Generated by tools/exports.py;',
                 '# presence observed black-box (tests/apps/texp.c), names from',
                 '# OpenWatcom import libraries and Wine (X11 licence, wine-20020228:',
                 '# Copyright (c) 1993-2002 the Wine project authors).',
                 '# The 2.11 column says only that the ordinal exists there: Windows 2.x',
                 '# uses some ordinals for other functions (e.g. USER 445, which is',
                 '# DefFrameProc on 3.1, has another name on 2.11).', '']
        for o in sorted(o31 | o211):
            conv, wname = wine.get(o, ('', ''))
            name = wat.get((mod, o)) or wname.upper() or '?'
            lines.append('%5d  %-3s  %-4s  %-9s %s' % (
                o, 'yes' if o in o31 else '-', 'yes' if o in o211 else '-', conv or '-', name))
        with open(os.path.join(outdir, mod + '.txt'), 'w') as f:
            f.write('\n'.join(lines) + '\n')
        print('%-9s 3.1: %4d  2.11: %4d  unnamed: %d' % (
            mod, len(o31), len(o211),
            sum(1 for o in o31 | o211 if not wat.get((mod, o)) and o not in wine)))


if __name__ == '__main__':
    main()
