def exact(code, src, dst):
    """The same character in the other code page, or None."""
    try:
        return bytes([code]).decode(src).encode(dst)[0]
    except (UnicodeDecodeError, UnicodeEncodeError):
        return None


def table(src, dst, observed):
    t = []
    for c in range(256):
        v = observed.get(c, exact(c, src, dst))
        if v is None:
            sys.exit('kbtables: no value for %02Xh (%s -> %s)' % (c, src, dst))
        t.append(v)
    return t


def emit(f, name, t):
    f.write('%s:\n' % name)
    for i in range(0, 256, 16):
        f.write('        db %s   ; %02Xh\n' % (', '.join('%03Xh' % v for v in t[i:i + 16]), i))


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    a2o = table('cp1252', 'cp437', A2O_OBSERVED)
    o2a = table('cp437', 'cp1252', O2A_OBSERVED)
    with open(sys.argv[1], 'w') as f:
        f.write('; generated by tools/kbtables.py: cp1252 <-> cp437 with Windows\n'
                '; 3.1\'s observed choices (see there); do not edit\n')
        emit(f, 'ansi_to_oem', a2o)
        emit(f, 'oem_to_ansi', o2a)


if __name__ == '__main__':
    main()
