#!/usr/bin/env python3
"""mkapiprobe - make tests/apps/tw2api.h, the list of calls TW2 checks on
Windows 2.x, from a program's link map (its imports) and the 3.1
ordinals (build/host/imports.txt).

usage: mkapiprobe.py PROGRAM.map > tests/apps/tw2api.h
"""
import re
import sys

ords = {}
for line in open('build/host/imports.txt'):
    p = line.split()
    if len(p) >= 3 and p[1].isdigit():
        ords[(p[0], p[2].upper())] = int(p[1])
text = open(sys.argv[1]).read()
sec = text[text.find('Imported Symbols'):]
names = sorted(set(re.findall(r'^([A-Z_][A-Z0-9_]+)\s+(KERNEL|USER|GDI|SHELL|KEYBOARD)\b', sec, re.M)))
print('/* generated by tools/mkapiprobe.py from %s */' % sys.argv[1])
for name, mod in names:
    print('    { "%s", "%s", %d },' % (mod, name, ords.get((mod, name), 0)))
