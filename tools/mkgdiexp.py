#!/usr/bin/env python3
"""mkgdiexp - the export table of w16's GDI.EXE (gdi/).

Every ordinal Windows 3.1's GDI exports (docs/exports/GDI.txt, "yes" in
the 3.1 column; names as the real module's name tables have them) is
exported: by the C function implementing it, found in gdi/*.c by its
"/* GDI.n */" comment (or the ATTR/ORGEXT/GETPT macros of gdi/dc.c), or
else by a stub that records the call (gdi_unimpl) and returns 0.

The argument bytes of each export (Pascal: the callee pops them) are
checked against Wine's gdi.spec (tests/gdi/gdi.spec, X11 licence): a C
function whose parameters add up differently is an error. Stubs pop
what the spec says; ordinals the spec lists only as "stub" pop nothing
(UNVERIFIED for those).

usage: mkgdiexp.py OUT.lnk OUT.asm
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
from mkgdlog import read_wine  # noqa: E402

FOUR = {'DWORD', 'LONG', 'long', 'COLORREF', 'FARPROC', 'LPVOID', 'LPSTR', 'LPCSTR'}


def arg_bytes(params):
    params = params.strip()
    if params in ('', 'void'):
        return 0
    n = 0
    for p in params.split(','):
        p = p.strip()
        toks = re.findall(r'\w+', p)
        if '*' in p or any(t in FOUR for t in toks):
            n += 4
        else:
            n += 2
    return n


def implemented():
    out = {}
    for f in sorted(glob.glob(os.path.join(ROOT, 'gdi', '*.c'))):
        s = open(f).read()
        for m in re.finditer(r'GDIAPI\s+(\w+)\s*\(([^)]*)\)\s*/\*\s*GDI\.(\d+)\s*\*/', s):
            out[int(m.group(3))] = (m.group(1), arg_bytes(m.group(2)), f)
        for m in re.finditer(r'^ATTR\((\w+),\s*(\d+),', s, re.M):
            out[int(m.group(2))] = ('Get' + m.group(1), 2, f)
        for m in re.finditer(r'^ORGEXT\((\w+),\s*(\d+),', s, re.M):
            out[int(m.group(2))] = (m.group(1), 6, f)
        for m in re.finditer(r'^GETPT\((\w+),\s*(\d+),', s, re.M):
            out[int(m.group(2))] = (m.group(1), 2, f)
    return out


def main():
    lnk, asm = sys.argv[1], sys.argv[2]
    names = {}
    for line in open(os.path.join(ROOT, 'docs', 'exports', 'GDI.txt')):
        f = line.split()
        if f and f[0].isdigit() and f[1] == 'yes':
            names[int(f[0])] = f[-1]
    spec = {o: (n, m, a) for o, n, m, a in read_wine(os.path.join(ROOT, 'tests', 'gdi', 'gdi.spec'))}
    impl = implemented()
    L = ['# generated by tools/mkgdiexp.py: GDI.EXE\'s exports']
    A = ['; generated by tools/mkgdiexp.py: the exports w16\'s GDI does not implement yet',
         '        bits 16', '        cpu 286',
         'segment ENTRY_TEXT public align=16 class=CODE use16',
         'extern gdi_unimpl_entry']
    bad = 0
    for o in sorted(names):
        name = names[o]
        if name in ('?', '-'):
            name = f'GDI_ORD_{o}'
        sb = None
        if o in spec and spec[o][1] == 'log':
            sb = sum({'w': 2, 'l': 4, 'p': 4}[c] for c in spec[o][2])
        if o == 59:                     # WEP: entry.asm
            L.append('export WEP.59=WEP resident')
            continue
        if o == 46:                     # __GP: KERNEL's fault table (entry.asm)
            L.append('export __GP.46=GDI_GP resident')
            continue
        if o in impl:
            fn, nb, src = impl[o]
            if sb is not None and nb != sb:
                print(f'mkgdiexp: GDI.{o} {fn} ({os.path.basename(src)}) takes {nb} argument '
                      f'bytes, Wine\'s spec {sb}', file=sys.stderr)
                bad = 1
            L.append(f'export {name}.{o}={fn.upper()}')
        else:
            A.append(f'global S_{o}')
            A.append(f'S_{o}:  push word {o}')
            A.append('        call gdi_unimpl_entry')
            A.append('        xor ax, ax')
            A.append('        cwd')
            A.append(f'        retf {sb or 0}')
            L.append(f'export {name}.{o}=S_{o}')
    if bad:
        sys.exit(1)
    open(lnk, 'w').write('\n'.join(L) + '\n')
    open(asm, 'w').write('\n'.join(A) + '\n')
    print(f'mkgdiexp: {len(impl)} implemented, {len(names) - len(impl) - 1} stubs')


if __name__ == '__main__':
    main()
