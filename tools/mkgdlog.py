#!/usr/bin/env python3
"""mkgdlog - generate a logging stand-in module (GD1, GD2; tests/gdi/).

A stand-in exports the same ordinals and names as a real module and
forwards every call to it (a copy of the real file whose module name was
changed in its NE resident-name table); on the way in and out it records
the call (tests/gdi/gdlog.c). Black-box observation of the interface
between two Windows modules, e.g. GDI and the display driver.

usage: mkgdlog.py [--wine] [--only EXPORTS.txt] SPEC REALMODULE OUT.asm OUT.lnk MODNAME [DESCRIPTION]

SPEC lines: "ordinal NAME mode params" (see tests/gdi/display.spec), or a
Wine .spec file (X11 licence, wine-20020228) with --wine: its argument
types give the parameters (word/s_word/... = w, long = l, ptr/str/segptr/
segstr = p), and every function is logged.
"""
import re
import sys

TYPES = {'word': 'w', 's_word': 'w', 'long': 'l', 'ptr': 'p', 'str': 'p',
         'segptr': 'p', 'segstr': 'p'}


def read_spec(path):
    out = []
    for line in open(path):
        line = line.split('#', 1)[0].strip()
        if not line:
            continue
        f = line.split()
        out.append((int(f[0]), f[1], f[2], ''.join(f[3:])))
    return out


def read_wine(path):
    text = open(path).read()
    out = []
    # join continuation lines
    text = re.sub(r'\n\s+(?=[^\d\s])', ' ', text)
    for line in text.splitlines():
        line = line.split('#', 1)[0].strip()
        m = re.match(r'(\d+)\s+(pascal16|pascal|register)\s+(\w+)\s*\(([^)]*)\)', line)
        if m:
            args = ''.join(TYPES[a] for a in m.group(4).split())
            mode = 'log' if m.group(2) != 'register' else 'raw'
            out.append((int(m.group(1)), m.group(3).upper(), mode, args))
            continue
        m = re.match(r'(\d+)\s+(stub|equate|variable)\s+(\w+)', line)
        if m:
            out.append((int(m.group(1)), m.group(3).upper(), 'raw', ''))
    return out


def main():
    a = sys.argv[1:]
    wine = '--wine' in a
    if wine:
        a.remove('--wine')
    only = None
    if '--only' in a:
        i = a.index('--only')
        only = a[i + 1]
        del a[i:i + 2]
    spec, real, asm, lnk, modname = a[:5]
    desc = a[5] if len(a) > 5 else modname
    ents = read_wine(spec) if wine else read_spec(spec)
    if only:
        # export exactly the ordinals the real module has (docs/exports
        # table, "yes" in the 3.1 column); those the spec lacks are raw
        have = {}
        for line in open(only):
            f = line.split()
            if f and f[0].isdigit() and f[1] == 'yes':
                have[int(f[0])] = f[-1].upper()
        ents = [e for e in ents if e[0] in have]
        known = {e[0] for e in ents}
        ents += [(o, n, 'raw', '') for o, n in have.items() if o not in known]
        ents.sort()
    A = ['; generated by tools/mkgdlog.py from ' + spec, '        bits 16', '        cpu 286',
         '%include "gdlog.inc"', 'segment _TEXT']
    L = ['# generated by tools/mkgdlog.py from ' + spec, 'format windows dll',
         'option quiet', 'option start=gdl_libentry', 'option heapsize=1k',
         f'option modname={modname}', f"option description '{desc}'",
         'library windows.lib',
         'segment type code fixed preload', 'segment type data fixed preload']
    names = []
    for i, (o, name, mode, args) in enumerate(ents):
        sym = f'R_{o}'
        A.append(f'extern {sym}')
        L.append(f'import {sym} {real}.{o}')
        A.append(f'global E_{o}')
        if mode == 'pass':
            A.append(f'E_{o}: jmp (seg {sym}):{sym}')
        else:
            A.append(f'E_{o}: push word {i}')
            A.append(f'        push word {i}')
            A.append('        jmp gdl_common')
        res = ' resident' if name in ('WEP',) else ''
        L.append(f'export {name}.{o}=E_{o}{res}')
        nbytes = sum({'w': 2, 'l': 4, 'p': 4}[c] for c in args)
        names.append((o, name, mode, args, nbytes))
    A.append('global gdl_realtab')
    A.append('gdl_realtab:')
    for o, *_ in names:
        A.append(f'        dw R_{o}, seg R_{o}')
    # the table gdlog.c reads: ordinal, mode (0 log, 1 raw, 2 pass),
    # argument bytes, name, parameter letters
    A.append('segment _DATA')
    A.append('global _gdl_count, _gdl_tab')
    A.append(f'_gdl_count dw {len(names)}')
    A.append('_gdl_tab:')
    for i, (o, name, mode, args, nb) in enumerate(names):
        A.append(f'        dw {o}, {["log", "raw", "pass"].index(mode)}, {nb}, gdn{i} wrt DGROUP, DGROUP, gda{i} wrt DGROUP, DGROUP')
    A.append('segment CONST')
    for i, (o, name, mode, args, nb) in enumerate(names):
        A.append(f'gdn{i} db "{name}", 0')
        A.append(f'gda{i} db "{args}", 0')
    open(asm, 'w').write('\n'.join(A) + '\n')
    open(lnk, 'w').write('\n'.join(L) + '\n')


if __name__ == '__main__':
    main()
