#!/usr/bin/env python3
"""mkinterpose - generate a forwarding module for probe US1 (ARCHITECTURE.md 10).

The generated module (NASM source + wlink directives) has module name NAME
and exports every code entry of the real module REAL (same ordinals and
names, resident names stay resident); each export records the call through
USTRACE.DLL (tests/user/ustrace.c) and jumps to the same ordinal of module
TARGET with every register, the flags and the stack exactly as the caller
left them. With --ret, the return is recorded too: the return address is
swapped for a stub that records the registers the callee returned and goes
back to the caller (not for calls that may switch tasks, see ustrace.c).

REAL is only read for its entry table and names (NE header data). Argument
layouts (where far pointers are, how many bytes the callee pops) come from
Wine's X11-licensed spec files (wine-20020228, ARCHITECTURE.md 3).

usage: mkinterpose.py --name USER --target XUSR --real USER.EXE --modid 0
                      [--spec user.spec] [--ret all|ORD,ORD,...] OUTDIR
Writes OUTDIR/NAME.asm and OUTDIR/NAME.lnk.
"""
import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from neimports import NE  # noqa: E402

SIZES = {'word': 2, 's_word': 2, 'long': 4, 'ptr': 4, 'str': 4, 'segptr': 4, 'segstr': 4}
PTRS = {'ptr', 'str', 'segptr', 'segstr'}


def spec_args(path):
    """ordinal -> (pointer word mask, argument bytes) or None (unknown)."""
    out = {}
    if not path or not os.path.exists(path):
        return out
    for line in open(path, encoding='latin-1'):
        m = re.match(r'^\s*(\d+)\s+(pascal16|pascal)\s+\S+\(([^)]*)\)', line)
        if not m:
            continue
        args = m.group(3).split()
        if any(a not in SIZES for a in args):
            continue
        mask, w = 0, 0
        for a in reversed(args):            # last argument is nearest
            if a in PTRS:
                mask |= 1 << w
            w += SIZES[a] // 2
        out[int(m.group(1))] = (mask, 2 * w)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--name', required=True)
    ap.add_argument('--target', required=True)
    ap.add_argument('--real', required=True)
    ap.add_argument('--modid', type=int, required=True)
    ap.add_argument('--spec')
    ap.add_argument('--ret', default='')
    ap.add_argument('--args', action='append', default=[],
                    help='ORD:type,type,... (word, long, ptr, ...; left to right) where '
                         'the spec has none, e.g. from the DDK documentation')
    ap.add_argument('outdir')
    a = ap.parse_args()
    ne = NE(a.real)
    names = {o: (s, True) for s, o in ne.res_names[1:]}
    names.update({o: (s, False) for s, o in ne.nonres_names[1:]})
    ents = ne.entries()
    args = spec_args(a.spec)
    for spec in a.args:
        o, _, types = spec.partition(':')
        mask, w = 0, 0
        for t in reversed([t for t in types.split(',') if t]):
            if t in PTRS:
                mask |= 1 << w
            w += SIZES[t] // 2
        args[int(o)] = (mask, 2 * w)
    ords = []
    for o in sorted(ents):
        seg = ents[o][0]
        if seg == 'const' or ne.segs[seg - 1][2] & 1:
            continue                    # data and constant entries: not code
        if names.get(o, ('', 0))[0].upper() == '__GP':
            continue
        ords.append(o)
    rets = set(ords) if a.ret == 'all' else {int(x) for x in a.ret.split(',') if x}
    os.makedirs(a.outdir, exist_ok=True)
    L = [f'; {a.name}: US1 forwarding module for {a.target} (generated by tools/mkinterpose.py)',
         '        bits 16', '        cpu 286',
         'segment _TEXT public align=16 class=CODE use16',
         'extern TRREC, TRRET', 'global libentry',
         'libentry:', '        mov ax, 1', '        retf']
    for i, o in enumerate(ords):
        L += [f'global T_{o}', f'T_{o}:', f'        push word {i}', '        push cs', '        push cs',
              '        jmp thunk_common']
    L += ['thunk_common:',
          '        push bp', '        mov bp, sp', '        pushf', '        pusha', '        push ds',
          '        push es', '        cld',
          '        mov bx, [bp+6]', '        shl bx, 2',
          '        mov ax, [cs:targets+bx]', '        mov [bp+2], ax',
          '        mov ax, [cs:targets+bx+2]', '        mov [bp+4], ax',
          '        shr bx, 1',
          f'        push word {a.modid}',
          '        push word [cs:ords+bx]', '        push word [cs:pmask+bx]',
          '        push word [cs:abytes+bx]', '        push word [cs:wantret+bx]',
          '        push cs', '        push retstub',
          '        push ss', '        lea ax, [bp-22]', '        push ax',
          '        call far TRREC',
          '        pop es', '        pop ds', '        popa', '        popf', '        pop bp',
          '        retf 2',
          'retstub:',
          '        push cs', '        push cs', '        push bp', '        mov bp, sp', '        pushf',
          '        pusha', '        push ds', '        push es', '        cld',
          '        push ss', '        lea ax, [bp-22]', '        push ax',
          '        call far TRRET',
          '        pop es', '        pop ds', '        popa', '        popf', '        pop bp',
          '        retf']
    L.append('align 2')
    L.append('targets:')
    for o in ords:
        L += [f'extern X_{o}', f'        dw X_{o}, seg X_{o}']
    for tab, fn in (('ords', lambda o: o), ('pmask', lambda o: args.get(o, (0, 0))[0]),
                    ('abytes', lambda o: args[o][1] if o in args else 0xFFFF),
                    ('wantret', lambda o: 1 if o in rets else 0)):
        L.append(f'{tab}:')
        vals = [fn(o) for o in ords]
        for k in range(0, len(vals), 16):
            L.append('        dw ' + ', '.join(str(v) for v in vals[k:k + 16]))
    open(os.path.join(a.outdir, a.name + '.asm'), 'w').write('\n'.join(L) + '\n')
    K = [f'# {a.name}: US1 forwarding module for {a.target} (tools/mkinterpose.py)',
         'format windows dll', 'option quiet', f'option modname={a.name}', 'option start=libentry',
         f"option description 'w16 US1 forwarder for {a.target}'",
         'segment type code fixed preload',
         'import TRREC USTRACE.1', 'import TRRET USTRACE.2']
    used = set()
    for o in ords:
        nm, res = names.get(o, (f'ORD_{o}', False))
        if nm.upper() in used:
            nm = f'{nm}_{o}'
        used.add(nm.upper())
        K.append(f'export {nm}.{o}=T_{o}' + (' resident' if res else ''))
        K.append(f'import X_{o} {a.target}.{o}')
    open(os.path.join(a.outdir, a.name + '.lnk'), 'w').write('\n'.join(K) + '\n')
    print(f'{a.name}: {len(ords)} entries forwarded to {a.target}, {len(rets & set(ords))} with returns')


if __name__ == '__main__':
    main()
