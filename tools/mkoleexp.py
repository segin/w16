#!/usr/bin/env python3
"""mkoleexp - the export table of w16's OLECLI.DLL (ole/olecli/).

Every ordinal Windows 3.1's OLECLI exports (docs/exportdb/exports.csv; names
and residency as the real module's NE tables have them) is exported:

  - by the function of the same name (OLEAPI functions in ole/olecli/*.c;
    OpenWatcom upper-cases Pascal names: OleCreate is OLECREATE);
  - or by the function ALIASES names (the MF/BM/DIB/GEN/PB entries share
    the LE methods; the PB creation entries are the DEF functions);
  - ordinals without a name by OLECLI_NONAME (code) or OLECLI_NONAME_DATA
    (data), exported as OLECLI_<n>; tools/nestripnames.py then removes
    those names, so that they are ordinal-only as in the original.

usage: mkoleexp.py OUT.lnk
"""
import csv
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

ALIASES = {
    'LEQUERYTYPE': 'OBJQUERYTYPE',
    'PBLOADFROMSTREAM': 'DEFLOADFROMSTREAM',
    'PBCREATEFROMCLIP': 'DEFCREATEFROMCLIP',
    'PBCREATELINKFROMCLIP': 'DEFCREATELINKFROMCLIP',
    'PBCREATEFROMTEMPLATE': 'DEFCREATEFROMTEMPLATE',
    'PBCREATE': 'DEFCREATE',
    'PBDRAW': 'LEDRAW',
    'PBQUERYBOUNDS': 'LEQUERYBOUNDS',
    'PBCOPYTOCLIPBOARD': 'LECOPYTOCLIPBOARD',
    'PBCREATEFROMFILE': 'DEFCREATEFROMFILE',
    'PBCREATELINKFROMFILE': 'DEFCREATELINKFROMFILE',
    'PBENUMFORMATS': 'LEENUMFORMAT',
    'PBGETDATA': 'LEGETDATA',
    'PBCREATEINVISIBLE': 'DEFCREATEINVISIBLE',
}
# the static objects' families share the LE methods
for fam in ('MF', 'BM', 'DIB', 'GEN'):
    for m in ('RELEASE', 'GETDATA', 'SETDATA', 'SAVETOSTREAM', 'CLONE', 'EQUAL', 'COPY',
              'QUERYBOUNDS', 'DRAW', 'ENUMFORMAT', 'CHANGEDATA'):
        ALIASES[fam + m] = 'LE' + m


def defined():
    names = set()
    for f in glob.glob(os.path.join(ROOT, 'ole', 'olecli', '*.c')):
        s = open(f).read()
        for m in re.finditer(r'\bOLEAPI\s+(\w+)\s*\(', s):
            names.add(m.group(1).upper())
    for f in glob.glob(os.path.join(ROOT, 'ole', 'olecli', '*.asm')):
        for m in re.finditer(r'^global\s+(\w+)', open(f).read(), re.M):
            names.add(m.group(1))
    return names


def main():
    have = defined()
    rows = [r for r in csv.DictReader(open(os.path.join(ROOT, 'docs', 'exportdb', 'exports.csv')))
            if r['install'] == 'win31' and r['module'] == 'OLECLI']
    out = ['# generated by tools/mkoleexp.py from docs/exportdb/exports.csv']
    missing = []
    for r in rows:
        o = int(r['ordinal'])
        name = r['name']
        res = ' resident' if r['residency'] == 'resident' else ''
        if not name:
            sym = 'OLECLI_NONAME_DATA' if r['kind'] == 'data' else 'OLECLI_NONAME'
            out.append('export OLECLI_%d.%d=%s' % (o, o, sym))
            continue
        sym = name if name in have else ALIASES.get(name)
        if not sym or sym not in have:
            missing.append(name)
            continue
        if sym == name:
            out.append('export %s.%d%s' % (name, o, res))
        else:
            out.append('export %s.%d=%s%s' % (name, o, sym, res))
    if missing:
        sys.exit('mkoleexp: no function for ' + ' '.join(missing))
    open(sys.argv[1], 'w').write('\n'.join(out) + '\n')


main()
