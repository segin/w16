#!/usr/bin/env python3
"""mkuserexp - export list and stubs for w16's USER.EXE (user/).

Every USER ordinal of user/ordinals.txt is exported under its Windows 3.1
name. An ordinal whose function exists in the objects as a public symbol
of that name (a far pascal C function GetFocus is GETFOCUS; wsprintf, the
one C-convention export, is _wsprintf), or as U_<NAME> for functions
windows.h does not declare, exports that; every other ordinal exports a
stub, a label of the same name in the generated assembly (so USER's own
calls reach it too), which notes the call (UNIMPL in user/stub.c) and
returns 0 in DX:AX, popping the argument bytes the table gives.

usage: mkuserexp.py ORDINALS OUT.lnk OUT.asm OBJ...
"""
import struct
import sys


def publics(path):
    d, p, out = open(path, 'rb').read(), 0, set()
    while p + 3 <= len(d):
        typ, ln = d[p], struct.unpack_from('<H', d, p + 1)[0]
        body = d[p + 3:p + 3 + ln - 1]
        p += 3 + ln
        if typ not in (0x90, 0x91):
            continue
        q = 0

        def index(q):
            b = body[q]
            return ((b & 0x7F) << 8 | body[q + 1], q + 2) if b & 0x80 else (b, q + 1)
        grp, q = index(q)
        seg, q = index(q)
        if grp == 0 and seg == 0:
            q += 2
        while q < len(body):
            n = body[q]
            name = body[q + 1:q + 1 + n].decode('latin-1')
            q += 1 + n + (2 if typ == 0x90 else 4)
            _, q = index(q)
            out.add(name)
    return out


def main():
    ords, lnk, asm, objs = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4:]
    pubs = set()
    for o in objs:
        pubs |= publics(o)
    rows = []
    for line in open(ords):
        f = line.split()
        if f and f[0].isdigit():
            rows.append((int(f[0]), f[1], f[2] == 'res', f[3]))
    L = ['# generated by tools/mkuserexp.py from user/ordinals.txt']
    A = ['; generated by tools/mkuserexp.py: stubs for the USER ordinals w16 does',
         '; not implement yet (user/stub.c)', '        bits 16', '        cpu 286',
         'segment STUB_TEXT public align=16 class=CODE use16', 'extern UNIMPL', '']
    nimpl = 0
    special = {'_WSPRINTF': '_wsprintf'}
    for o, name, res, args in rows:
        sym = special.get(name, name)
        if sym in pubs or 'U_' + name in pubs:
            sym = sym if sym in pubs else 'U_' + name
            nimpl += 1
        else:
            n = int(args) if args.isdigit() else 0
            A += [f'global {sym}', f'{sym}:', f'        push word {o}', f'        push word {n}',
                  '        jmp stub_common']
        L.append(f'export {name}.{o}={sym}' + (' resident' if res else ''))
    A += ['stub_common:',
          '        push bp', '        mov bp, sp',          # [bp+2] n, [bp+4] ord, [bp+6] ret
          '        pusha', '        push ds', '        push es',
          '        push word [bp+4]', '        call far UNIMPL',
          '        pop es', '        pop ds', '        popa',
          '        push si', '        mov si, [bp+2]',
          '        mov ax, [bp+8]', '        mov [bp+si+8], ax',
          '        mov ax, [bp+6]', '        mov [bp+si+6], ax',
          '        lea ax, [bp+si+6]', '        pop si',
          '        mov bp, [bp]', '        mov sp, ax',
          '        xor ax, ax', '        xor dx, dx', '        retf']
    open(lnk, 'w').write('\n'.join(L) + '\n')
    open(asm, 'w').write('\n'.join(A) + '\n')
    print(f'USER: {nimpl} of {len(rows)} ordinals implemented')


if __name__ == '__main__':
    main()
