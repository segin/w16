#!/usr/bin/env python3
"""Turn reference observations into expected values for a test program.

usage: tools/obsref.py LOG [LOG...] > tests/apps/tkNref.h

Reads TK.LOG output of tests/refrun.sh (one or more runs, e.g. Standard
and 386 Enhanced mode) and writes a C initializer list
    { "name", 0xVVVV },
for every "OBS name=VVVV" line. Memory dumps (name@offset) and
layout-dependent values (OBS ~name) are skipped. A name whose value differs
between the logs is left out and reported on stderr. A name only some logs
have (e.g. a probe that names its observations by configuration, like
TK6's "87." and "em.") is compared among those logs only.

usage: tools/obsref.py --k286 K286LOG [-x|-X REGEX]... LOG [LOG...] \
           > tests/apps/tkNref286.h

The table of values that differ under KRNL286 (TK_REF286, see
tests/apps/tklog.h): every name of K286LOG (a run with REFRUN_KRNL286=1)
whose value differs from the table LOG... gives (or the existing table
tkNref.h, given instead of the logs), or that the table lacks.
Names matching a -x regular expression are written with skip set (not
checked): KRNL286 differs there in a way w16 does not implement. Names
matching -X are written with skip set even where the values agree:
KRNL286 varies between runs there.
"""
import re
import sys


def read(path):
    vals = {}
    order = []
    with open(path, encoding="latin-1") as f:
        for line in f:
            line = line.rstrip("\r\n")
            if not line.startswith("OBS ") or line.startswith("OBS ~"):
                continue
            name, sep, value = line[4:].rpartition("=")
            if not sep or "@" in name or len(value) != 4:
                continue
            try:
                v = int(value, 16)
            except ValueError:
                continue
            if name not in vals:
                order.append(name)
            vals[name] = v
    return order, vals


def read_h(path):
    """an existing table (tkNref.h)"""
    vals = {}
    with open(path, encoding="latin-1") as f:
        for line in f:
            m = re.match(r'\{ "(.*)", 0x([0-9A-Fa-f]{4})', line.strip())
            if m:
                name = m.group(1).replace('\\"', '"').replace("\\\\", "\\")
                vals[name] = int(m.group(2), 16)
    return vals


def table(paths):
    """the names and values a reference table of these logs (or the
    existing table tkNref.h) holds"""
    if len(paths) == 1 and paths[0].endswith(".h"):
        return read_h(paths[0])
    order, first = [], {}
    logs = [read(p) for p in paths]
    for o, vals in logs:
        for name in o:
            if name not in first:
                order.append(name)
                first[name] = vals[name]
    others = [vals for _, vals in logs]
    return {n: first[n] for n in order
            if all(o.get(n, first[n]) == first[n] for o in others)}


def cstr(name):
    return name.replace("\\", "\\\\").replace('"', '\\"')


def k286(args):
    k286log = args.pop(0)
    skip, always = [], []
    while args and args[0] in ("-x", "-X"):
        (skip if args.pop(0) == "-x" else always).append(re.compile(args.pop(0)))
    base = table(args)
    order, vals = read(k286log)
    print("/* Generated by tools/obsref.py --k286 from a Windows 3.1 KRNL286")
    print(" * reference run (Standard mode, tests/refrun.sh REFRUN_KRNL286=1):")
    print(" *   " + k286log.rsplit("/", 1)[-1])
    print(" * the values that differ from the table of:")
    for p in args:
        print(" *   " + p.rsplit("/", 1)[-1])
    if skip:
        print(" * Not checked where they differ (w16 does not implement KRNL286):")
        for r in skip:
            print(" *   -x '%s'" % r.pattern)
    if always:
        print(" * Not checked at all (KRNL286 varies between runs):")
        for r in always:
            print(" *   -X '%s'" % r.pattern)
    print(" * Do not edit; regenerate when the probe changes. */")
    for name in order:
        v = vals[name]
        a = any(r.search(name) for r in always)
        if base.get(name) == v and not a:
            continue
        s = a or any(r.search(name) for r in skip)
        print('{ "%s", 0x%04X%s },' % (cstr(name), v, ", 1" if s else ""))


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    if sys.argv[1] == "--k286":
        k286(sys.argv[2:])
        return
    order, first = [], {}
    logs = [read(p) for p in sys.argv[1:]]
    for o, vals in logs:
        for name in o:
            if name not in first:
                order.append(name)
                first[name] = vals[name]
    others = [vals for _, vals in logs]
    print("/* Generated by tools/obsref.py from Windows 3.1 reference runs:")
    for p in sys.argv[1:]:
        print(" *   " + p.rsplit("/", 1)[-1])
    print(" * Do not edit; regenerate when the probe changes. */")
    for name in order:
        v = first[name]
        if any(o.get(name, v) != v for o in others):
            print("obsref: %s differs between runs, skipped" % name, file=sys.stderr)
            continue
        cname = name.replace("\\", "\\\\").replace('"', '\\"')
        print('{ "%s", 0x%04X },' % (cname, v))


if __name__ == "__main__":
    main()
