#!/usr/bin/env python3
"""sndtables - the sound driver's note table (drivers/sound/sound.asm).

Note values 1-84 of the SOUND API are seven octaves of equal temperament;
on Windows 3.1's driver note 37 sounds C5 (523 Hz) and every value is a
semitone above the one before (measured: drivers/sound/README.md). The
8254's channel 2 divides 1193182 Hz, so each note's divisor is
1193182 / f rounded, f = 440 * 2 ** ((n - 34) / 12). Computed here, not
taken from any file.

usage: sndtables.py OUT.inc
"""
import sys

PIT = 1193182


def main():
    out = ['; generated by tools/sndtables.py: 8254 divisors of notes 1-84',
           'notediv:']
    for n in range(1, 85):
        f = 440.0 * 2 ** ((n - 34) / 12)
        out.append('        dw %5d                     ; note %2d, %8.2f Hz' % (round(PIT / f), n, f))
    open(sys.argv[1], 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
