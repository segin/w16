#!/bin/sh
# Regenerate docs/win386-services.md: the VxD tables and service-usage
# matrix of the reference installs, from readexe's LE/DDB output.
# Needs the reference installs (.tools/ref) and, for service names, Ralf
# Brown's Interrupt List release 61 INTERRUP.F (RBIL=path; optional).
set -e
top=$(cd "$(dirname "$0")/.." && pwd)
ref=${REF:-$top/.tools/ref}
[ -d "$ref" ] || ref=$(cd "$top/../../.." 2>/dev/null && pwd)/.tools/ref
out=$top/build/readexe-w16
mkdir -p "$out"
cc ${CFLAGS:--O2} -I"$top/tools/readexe" -o "$out/readexe" \
    "$top/tools/readexe/readexe.c" "$top/tools/readexe/err.c" 2>/dev/null
rbil=${RBIL:--}
w=$ref/win31/cdrive/WINDOWS/SYSTEM
f=$ref/wfw311a/cdrive/WINDOWS/SYSTEM
python3 -I "$top/tools/vxdmap.py" "$out/readexe" "$rbil" "$out/win31.md" \
    "Windows 3.1:$w/WIN386.EXE" "Windows 3.1:$w/VTDAPI.386"
set --
for x in "$f"/*.386; do set -- "$@" "Windows for Workgroups 3.11:$x"; done
python3 -I "$top/tools/vxdmap.py" "$out/readexe" "$rbil" "$out/wfw.md" \
    "Windows for Workgroups 3.11:$f/WIN386.EXE" "$@"
{
    echo "# WIN386.EXE: VxD tables and service-usage matrix"
    echo
    echo "Generated by \`tools/vxdmap.sh\` (readexe's LE/DDB dump, \`tools/readexe\`, read by \`tools/vxdmap.py\`); see docs/win386-vxds.md for how to read it and for the sources."
    echo
    sed 's/^## /## /' "$out/win31.md"
    echo
    cat "$out/wfw.md"
} > "$top/docs/win386-services.md"
echo "wrote docs/win386-services.md"
